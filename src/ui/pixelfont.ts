export function hasGlyph(ch: string): boolean {
  return ch.toUpperCase() in G;
}

/** SVG markup for a label in the tile font. Height fills the box; width follows the text. */
export function pixelText(text: string, color = 'currentColor'): string {
  const chars = [...text.toUpperCase()];
  const w = chars.length * 6 - 1;
  let rects = '';
  chars.forEach((ch, i) => {
    const g = G[ch] ?? G['?_'];
    g.forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') rects += `<rect x="${i * 6 + x}" y="${y}" width="1.02" height="1.02"/>`;
    });
  });
  return `<svg class="px" viewBox="0 0 ${w} 8" preserveAspectRatio="xMidYMid meet" shape-rendering="crispEdges" fill="${color}" aria-label="${text.replace(/"/g, '')}" role="img">${rects}</svg>`;
}
