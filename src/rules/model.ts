import type { CharacterId, FakeKind } from '../types';
import type { Button, DrawType, PromptType } from './config';

export interface PromptPlan {
  type: PromptType;
  /** Countdown starts here; the prompt shows at t; it closes at end. */
  c: number;
  t: number;
  end: number;
  /** First time this type appears in the match: show a mini demo during the countdown. */
  demo: boolean;
  /** Buttons to press: 1, or orderLength directions for SEQUENCE. The same for both players. */
  keys: Button[];
  /** RELEASE: when the tile says LET GO (ms after t). */
  cueMs?: number;
  /** TIME IT: arc centre (ms after t), the same for both players. */
  arcMs?: number;
}

export interface FakePlan {
  t: number;
  kind: FakeKind;
}

/** Everything random about one exchange. Generated by the host and shared online. */
export interface ExchangePlan {
  seed: number;
  prompts: PromptPlan[];
  /** The standoff begins here: from now on ACTION is an early draw and UP is a feint. */
  standoffStart: number;
  /** The draw-type announcement (and first-time demo) ends here. */
  announceEnd: number;
  drawType: DrawType;
  drawDemo: boolean;
  fakes: FakePlan[];
  bellT: number;
  /** WHEEL, the same for both players: success arc centre (ms into a sweep), needle phase at the bell, direction. */
  wheel: { arc: number; start: number; dir: 1 | -1 };
}

/** A button going down or up. Heal (hold DOWN in READY) and feint (UP in the standoff) are read from these. */
export type InputEvent =
  | { t: number; kind: 'press'; slot: Button }
  | { t: number; kind: 'release'; slot: Button };

/** Effects that last exactly one exchange (the next one), then clear. They never stack. */
export interface StatusEffects {
  blind: boolean;   // starts the exchange with blindFlinches
  smoke: boolean;   // Dusty's smoke hides your prompt tiles
}

export interface PlayerState {
  character: CharacterId;
  hearts: number;
  healsLeft: number;
  status: StatusEffects;
  /** Sister Mercy's charge (consecutive blinds). */
  charge: number;
  fullHealUsed: boolean;
}

export interface MatchState {
  players: [PlayerState, PlayerState];
  exchange: number;
  /** Prompt and draw types already seen this match (no more demos for these). */
  seen: string[];
  winner: 0 | 1 | 'draw' | null;
}

export type PromptStatus = 'pending' | 'ok' | 'beaten' | 'miss' | 'slow';

export interface PromptOutcome {
  status: PromptStatus;
  /** Completion time (ok/beaten/slow) or the time the miss was decided. */
  t: number | null;
  /** First press time inside the window. */
  pressT: number | null;
  holding: boolean;
  /** MASH / IN ORDER progress, TIME IT not used. */
  count: number;
}

export interface FeintOutcome {
  by: 0 | 1;
  t: number;
  status: 'pending' | 'bit' | 'whiff';
  biteT: number | null;
}

export interface DrawOutcome {
  pressT: number;         // absolute exchange time the draw completed (WHEEL: the shot)
  reaction: number;       // ms after the bell
  effective: number;      // reaction + character draw delay
  perfect: boolean;
  jams: number;
  /** WHEEL: distance (ms) from the arc centre, and whether the shot was inside the arc. */
  dist?: number;
  inside?: boolean;
}

export type OutcomeKind = 'early' | 'reset' | 'shot' | 'trade' | 'blind' | 'will' | 'mutualBlind';

export interface Outcome {
  kind: OutcomeKind;
  actor: 0 | 1 | null;
  damage: [number, number];
  blinded: [boolean, boolean];
  perfect: [boolean, boolean];
  fake: FakePlan | null;
  t: number;
}

/** Per-player numbers for the draw at the bell (they shrink with flinches). */
export interface DrawWindow {
  /** RING: gold band width. WHEEL: perfect slice half-width. SPEED: perfect span. */
  perfect: number;
  /** WHEEL: success arc half-width (0 for other types). */
  arcHalf: number;
}

export interface ExchangeResult {
  done: boolean;
  /** READY: how far each player's DOWN hold is toward a heal (0..1). */
  healProgress: [number, number];
  healed: [boolean, boolean];
  hearts: [number, number];
  drunk: [boolean, boolean];
  cigar: [boolean, boolean];
  will: [boolean, boolean];
  lastStand: [boolean, boolean];
  prompts: [PromptOutcome, PromptOutcome][];
  feints: FeintOutcome[];
  flinches: [number, number];
  drawWin: [DrawWindow, DrawWindow];
  /** Back-compat alias: RING gold band width per player. */
  goldBand: [number, number];
  /** SPEED TAP progress per player. */
  speedCount: [number, number];
  draws: [DrawOutcome | null, DrawOutcome | null];
  outcome: Outcome | null;
}

export type WillChoice = 'vaporize' | 'heal';
